def set_text(paragraph, text):
    """Keep the bold label runs, replace everything after them with plain text."""
    runs = paragraph.runs
    label = 0
    while label < len(runs) and runs[label].bold:
        label += 1
    for run in runs[label:]:
        run.text = ""
    target = runs[label] if label < len(runs) else paragraph.add_run()
    target.text = (" " if label and not runs[label - 1].text.endswith(" ") else "") + text
    target.italic = False
    target.bold = False
    target.font.color.rgb = INK


def full_width(table, shares):
    """Spread a table over the text width by shares (the template's grid is narrow)."""
    from docx.oxml.ns import qn
    from docx.shared import Emu

    section = table._parent.part.document.sections[0]
    width = section.page_width - section.left_margin - section.right_margin
    widths = [Emu(int(width * share / sum(shares))) for share in shares]
    grid = table._tbl.tblGrid
    for col, w in zip(grid.findall(qn("w:gridCol")), widths):
        col.set(qn("w:w"), str(int(w.twips if hasattr(w, "twips") else w / 635)))
    for row in table.rows:
        for cell, w in zip(row.cells, widths):
            cell.width = w
    table.autofit = False


def fill_cell(cell, text):
    paragraph = cell.paragraphs[0]
    for run in paragraph.runs[1:]:
        run.text = ""
    run = paragraph.runs[0] if paragraph.runs else paragraph.add_run()
    run.text = text
    run.italic = False
    run.font.color.rgb = INK


def fill_rows(table, rows):
    """Fill body rows, adding rows by copying the last one when needed."""
    while len(table.rows) - 1 < len(rows):
        table._tbl.append(copy.deepcopy(table.rows[-1]._tr))
    for row, values in zip(table.rows[1:], rows):
        for cell, value in zip(row.cells, values):
            fill_cell(cell, value)


def main():
    d = docx.Document(TEMPLATE)
    paragraphs = d.paragraphs
    for p in paragraphs:
        for label, text in TEXT.items():
            if p.runs and p.runs[0].text.startswith(label) and p.runs[0].bold:
                set_text(p, text)
                if label == "Технологическая схема":
                    picture = d.add_paragraph()
                    picture.add_run().add_picture(str(HERE / "png" / "flow.png"), width=Cm(16.5))
                    p._p.addnext(picture._p)
                break

    # Функции прототипа: три подсказки + строка «не ограничено» → наш список.
    hints = [p for p in paragraphs if p.style.name == "Compact" and p.text.startswith("Функция")]
    for p, text in zip(hints, FUNCTIONS):
        set_text(p, text)
    last = hints[-1]
    for text in reversed(FUNCTIONS[len(hints):]):
        clone = copy.deepcopy(last._p)
        last._p.addnext(clone)
        set_text(docx.text.paragraph.Paragraph(clone, last._parent), text)
    for p in paragraphs:
        if p.text.strip().startswith(("Количество функций", "Количество результатов")):
            p._p.getparent().remove(p._p)

    tables = d.tables
    for row, value in zip(tables[0].rows[1:], CARD):
        fill_cell(row.cells[1], value)
    fill_rows(tables[1], RESULTS)
    for row, value in zip(tables[2].rows[1:], DATA):
        fill_cell(row.cells[1], value)
    for row, value in zip(tables[3].rows[1:], SECURITY):
        fill_cell(row.cells[1], value)
    fill_rows(tables[4], PLAN)
    fill_rows(tables[5], TEAM)
    for table, shares in zip(tables, ([1, 2], [3, 3, 3], [1, 3], [1, 2], [2, 3, 3, 3, 3], [2, 2, 4, 2])):
        full_width(table, shares)

    # Подсказка «Заполняется командой…» в готовом паспорте не нужна.
    for p in d.paragraphs:
        if p.text.startswith("Заполняется командой"):
            p._p.getparent().remove(p._p)
        if p.text.startswith("Код прозрачности — типовой паспорт проекта"):
            p.runs[0].text = "Код прозрачности — паспорт проекта «Риски в кадастре»"
            for run in p.runs[1:]:
                run.text = ""

    d.save(OUT)
    print(f"готово: {OUT.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main()
